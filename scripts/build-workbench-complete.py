"""Bundle the complete delivered EAF clips for offline node previews."""
import argparse
import base64
import hashlib
import json
from pathlib import Path

from importlib.util import module_from_spec, spec_from_file_location

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'output/imagegen/airboat-expression-study-20261120/transitions/eaf-analysis'
OUTPUT = ROOT / 'docs/product/expression-complete-data.js'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    spec = spec_from_file_location('catalog', ROOT / 'scripts/build-expression-workbench.py')
    module = module_from_spec(spec)
    spec.loader.exec_module(module)
    rows = json.loads((SOURCE / 'manifest.json').read_bytes())['candidate_assets']
    assets, profiles = {}, {}
    for row in rows:
        key = row['semantic']
        if key == 'neutral':
            continue  # Match the delivered firmware: neutral and idle share one EAF.
        raw = (SOURCE / row['file']).read_bytes()
        assert len(raw) == row['bytes'] and hashlib.sha256(raw).hexdigest() == row['sha256']
        meta = module.inspect_eaf(raw)
        assert meta['frames'] == row['frames']
        entry, body, exit_ = row['entry_frames'], row['loop_frames'], row['exit_frames']
        assert entry[0] == 0 < entry[1] == body[0] < body[1] == exit_[0] < exit_[1] == meta['frames']
        name = 'transition-' + key + '.eaf'
        assets[name] = {**meta, 'kind': 'complete', 'bytes': len(raw), 'sha256': row['sha256'],
                        'eaf': base64.b64encode(raw).decode('ascii')}
        profiles[key] = {'file': name, 'fps': 1000 / row['period_ms'], 'loop': True,
                         'range': body, 'fill': True, 'semantic': key,
                         'segments': {'entry': entry, 'performance': body, 'exit': exit_}}
    profiles['neutral'] = {**profiles['idle'], 'semantic': 'neutral'}
    payload = json.dumps({'assets': assets, 'profiles': profiles}, ensure_ascii=False, separators=(',', ':'))
    content = '// Generated by scripts/build-workbench-complete.py; actual delivered EAF bytes.\n'
    content += '(() => { const pack = ' + payload + ';\n'
    content += 'Object.assign(window.AIRBOAT_EXPRESSIONS.assets,pack.assets);\n'
    content += 'window.AIRBOAT_EXPRESSIONS.complete = pack.profiles; })();\n'
    if args.check:
        assert OUTPUT.read_text(encoding='utf-8') == content, 'Complete preview bundle is stale'
    else:
        OUTPUT.write_text(content, encoding='utf-8', newline='\n')
    print(f'Complete preview: {len(assets)} delivered EAFs, {len(profiles)} semantics, entry/performance/exit')


if __name__ == '__main__':
    main()
